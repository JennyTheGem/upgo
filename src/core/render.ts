import { isOpen, PHASE_LABEL, type GoalsFile, type Item, type Phase } from "./schema.ts"

const COLLAPSED: Phase[] = ["wayLater", "maybe"]

export const GENERATED_MARK = "<!-- Generated by upgo from goals.json. Never edit this file or goals.json by hand: use the upgo CLI. -->"

const indent = (s: string) => s.trim().replace(/\r?\n/g, "\n  ")

function itemLine(item: Item): string {
    const tags = [PHASE_LABEL[item.phase], item.status === "partial" ? "partial" : ""].filter(Boolean).join(", ")
    return `- \`${item.id}\` ${item.title} (${tags})`
}

// goals.json -> the slim goals.md agents auto-load. Open items only, one line each.
export function render(file: GoalsFile): string {
    const open = file.items.filter(isOpen)
    const live = file.sections.filter((s) => open.some((i) => i.section === s.n))
    const closed = file.sections.filter((s) => !live.includes(s))

    const out = [`# ${file.project}: goals`, "", GENERATED_MARK, ""]
    if (file.purpose?.trim()) out.push(file.purpose.trim(), "")
    out.push(
        "Open work only. Full item: `upgo show <id>`. Any slice: `upgo list --phase later,wayLater,maybe`, `--status done,dropped`, `--section <n>`, `--search <text>`.",
        "",
    )
    if (closed.length) out.push(`Closed sections: ${closed.map((s) => `§${s.n} ${s.title}`).join(" · ")}`, "")

    if (file.traps.length) {
        out.push("## Traps", "")
        for (const t of file.traps) out.push(`- **${t.title}**${t.body?.trim() ? ` ${indent(t.body)}` : ""}`)
        out.push("")
    }

    for (const s of live) {
        out.push(`## ${s.n}. ${s.title}`, "")
        const mine = open.filter((i) => i.section === s.n)
        for (const item of mine.filter((i) => !COLLAPSED.includes(i.phase))) out.push(itemLine(item))
        const counts = COLLAPSED.map((p) => [p, mine.filter((i) => i.phase === p).length] as const).filter(([, c]) => c > 0)
        if (counts.length) {
            const what = counts.map(([p, c]) => `${c} ${PHASE_LABEL[p]}`).join(", ")
            out.push(`- Plus ${what}: \`upgo list --section ${s.n} --phase ${counts.map(([p]) => p).join(",")}\``)
        }
        out.push("")
    }
    return out.join("\n").replace(/\n+$/, "\n")
}
